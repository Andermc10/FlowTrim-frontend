@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly storageKey = 'flowtrim-language';
  readonly language = signal<Language>(this.getInitialLanguage());

  translate(key: string, parameters: Record<string, string | number> = {}): string {
    const value = translations[this.language()][key] ?? translations.en[key] ?? key;
    return Object.entries(parameters).reduce(
      (result, [name, replacement]) => result.replaceAll(`{{${name}}}`, String(replacement)),
      value,
    );
  }

  toggleLanguage(): void {
    this.language.update((language) => (language === 'en' ? 'es' : 'en'));
    this.persistLanguage();
  }

  languageLabel(): string {
    return this.language() === 'en' ? this.translate('language.switchToSpanish') : this.translate('language.switchToEnglish');
  }

  languageName(): string {
    return this.language() === 'en' ? this.translate('language.english') : this.translate('language.spanish');
  }

  translateAssumption(value: string): string {
    const assumptions: Record<string, string> = {
      'Assumes constant prices.': 'simulator.assumePrices',
      'Excludes taxes, penalties and price changes.': 'simulator.excludeChanges',
      'Not guaranteed.': 'simulator.notGuaranteed',
    };
    return this.translate(assumptions[value] ?? value);
  }

  private getInitialLanguage(): Language {
    try {
      const stored = localStorage.getItem(this.storageKey);
      if (stored === 'en' || stored === 'es') {
        return stored;
      }
    } catch {
      // English remains the safe default when local storage is unavailable.
    }
    return 'en';
  }

  private persistLanguage(): void {
    try {
      localStorage.setItem(this.storageKey, this.language());
    } catch {
      // Language switching still works for the current session.
    }
  }
}
